// Converts data/vocab.psv into src/data/vocab.generated.ts, which the app
// loads into SQLite on first launch (and again whenever the list changes).
//
//   npm run vocab
//
// To grow toward the top 10,000 words, append lines to data/vocab.psv in
// frequency order (or write another converter that outputs the same format).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'data', 'vocab.psv');
const out = join(root, 'src', 'data', 'vocab.generated.ts');

const TYPES = new Set([
  'noun', 'pronoun', 'verb-ru', 'verb-u', 'verb-irr',
  'adj-i', 'adj-na', 'adverb', 'expression', 'question',
]);

const raw = readFileSync(src, 'utf8');
const words = [];
const seen = new Set();
const errors = [];

raw.split(/\r?\n/).forEach((line, i) => {
  const t = line.trim();
  if (!t || t.startsWith('#')) return;
  const parts = t.split('|').map((p) => p.trim());
  if (parts.length !== 5) {
    errors.push(`line ${i + 1}: expected 5 fields, got ${parts.length}`);
    return;
  }
  const [kanji, kana, meaning, type, context] = parts;
  if (!kana || !meaning || !context) errors.push(`line ${i + 1}: kana, meaning and context are required`);
  if (!TYPES.has(type)) errors.push(`line ${i + 1}: unknown type "${type}"`);
  const key = `${kanji}|${kana}`;
  if (seen.has(key)) errors.push(`line ${i + 1}: duplicate word ${kanji || kana}`);
  seen.add(key);
  words.push([kanji === kana ? '' : kanji, kana, meaning, type, context]);
});

// ---- sentences: japanese | kana | english | word=surface,word=surface
const sentPath = join(root, 'data', 'sentences.psv');
const byWritten = new Map(words.map((w, i) => [w[0] || w[1], i + 1]));
const sentences = [];
readFileSync(sentPath, 'utf8').split(/\r?\n/).forEach((line, i) => {
  const t = line.trim();
  if (!t || t.startsWith('#')) return;
  const parts = t.split('|').map((p) => p.trim());
  const where = `sentences.psv line ${i + 1}`;
  if (parts.length !== 4) {
    errors.push(`${where}: expected 4 fields, got ${parts.length}`);
    return;
  }
  const [jp, kana, en, targetsRaw] = parts;
  const targets = [];
  for (const pair of targetsRaw.split(',').map((x) => x.trim()).filter(Boolean)) {
    const [word, surface] = pair.split('=').map((x) => x.trim());
    const id = byWritten.get(word);
    if (!id) errors.push(`${where}: "${word}" is not in vocab.psv`);
    else if (!surface || !jp.includes(surface)) errors.push(`${where}: "${surface}" not found in the sentence`);
    else targets.push([id, surface]);
  }
  if (!targets.length) errors.push(`${where}: needs at least one target word`);
  sentences.push([jp, kana, en, targets]);
});

if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const version = createHash('sha1').update(JSON.stringify([words, sentences])).digest('hex').slice(0, 12);
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `// AUTO-GENERATED by scripts/build-vocab.mjs from data/vocab.psv. Do not edit by hand.\n` +
    `// Row format: [kanji, kana, meaning, type, context]; array index + 1 = frequency rank.\n` +
    `export const VOCAB_VERSION = '${version}';\n` +
    `export const VOCAB: readonly (readonly [string, string, string, string, string])[] = ${JSON.stringify(words, null, 0).replace(/\],\[/g, '],\n  [')};\n` +
    `// Row format: [japanese, kana, english, [[wordId, surface], ...]]\n` +
    `export const SENTENCES: readonly (readonly [string, string, string, readonly (readonly [number, string])[]])[] = ${JSON.stringify(sentences, null, 0).replace(/\]\]\],\[/g, ']]],\n  [')};\n`,
);
console.log(`Wrote ${words.length} words and ${sentences.length} sentences (version ${version}) to src/data/vocab.generated.ts`);
